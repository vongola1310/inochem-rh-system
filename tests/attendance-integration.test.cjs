function upload(start = '2026-09-22', end = '2026-09-24', minute = '11') {
  const data = form({ startDate: start, endDate: end })
  const dates = start === end ? [start] : ['2026-09-22', '2026-09-23', '2026-09-24']
  const ajusco = 'ID de Empleado,Nombre,Fecha,Primera Checada,Última Checada\n' + dates.map(date => `33126,Prueba,${date},08:${minute},17:00`).join('\n')
  const periferico = 'Person ID,Name,Time\n' + dates.map(date => `'33126,Prueba,${date} 08:20:00`).join('\n')
  data.set('AJUSCO', new Blob([ajusco]), 'ajusco.csv')
  data.set('PERIFERICO', new Blob([periferico]), 'periferico.csv')
  return data
}
