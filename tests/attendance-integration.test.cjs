async function ddl(client, sql) {
  // Se permite únicamente el SQL de los esquemas de este repositorio, sin referencias a public.
  assert.ok(!/"public"\s*\./i.test(sql))
  const statements = sql.split(';').map(statement => statement.replace(/^\s*--.*$/gm, '').trim()).filter(Boolean)
  for (const statement of statements) assert.match(statement, /^(CREATE|ALTER)\s/i)
  await client.$transaction(async tx => {
    await tx.$executeRawUnsafe(`SET LOCAL search_path TO "${schema}"`)
    const current = await tx.$queryRawUnsafe('SELECT current_schema() AS name')
    assert.equal(current[0].name, schema, 'El DDL debe usar exclusivamente su esquema temporal')
    for (const statement of statements) await tx.$executeRawUnsafe(statement)
  }, { timeout: 60000 })
}

